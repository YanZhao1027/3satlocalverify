#!/usr/bin/env python3
"""Bridge Python VE sampling to the original Lean prime-power Hermite reconstruction.

Source parser and VE sampler are not Lean-verified; the original Lean
Reconstruction.run and its separate formal theorem remain untouched.
This is a computational reproducibility test, not a fully verified extraction.
"""
from __future__ import annotations
import argparse,json,os,pathlib,subprocess,time
from sample_ve import violation_histogram
from native_sparse import parse_dimacs

ROOT=pathlib.Path(__file__).resolve().parent
PROJECT=pathlib.Path.home()/'eth-lean-check-20261027/openai-math/lean'
EXPERIMENT=ROOT.parent

def isprime(n):
    if n<2:return False
    return not any(n%d==0 for d in range(2,int(n**.5)+1))


def generate(src:pathlib.Path,q:int,mu:int,D:int):
    n,F,m=parse_dimacs(src)
    H,stats=violation_histogram(n,F,max_width=19)
    Q=(m+1 + D-1)//D
    if not isprime(q) or Q>q:
        raise ValueError(f'need prime q and q>=Q, got q={q} Q={Q}')
    if D<1 or D>8 or mu<1 or mu>20:raise ValueError('invalid order/precision')
    modulus=q**mu
    if modulus<=2**n:
        raise ValueError(f'residue modulus {modulus} is too small for all coefficients (2^n={2**n})')
    coeffs=list(H)+[0]*max(0,Q*D-len(H))
    stem=src.stem.replace('-','_')
    outfile=ROOT/'generated'/f've_crt_{stem}_q{q}_mu{mu}_d{D}.lean'
    outfile.parent.mkdir(parents=True,exist_ok=True)
    module='''import HermiteKernel

/-! Exact coefficients generated by the standalone Python VE implementation.
    This generated constant table is not itself proved from DIMACS by Lean.
    Original OpenAI Reconstruction.run receives these verified-test inputs. -/
namespace VECrtGenerated

open OAI.Algorithms.SubexponentialSAT
open OAI.Algorithms.SubexponentialSAT.SqrtLog

def hist : List Nat := '''+repr(coeffs)+f'''

def result : List (ZMod {modulus}) × Nat :=
  Reconstruction.run (PaperKernel.ops {modulus})
    (fun i : Fin {Q} => (i.val : ZMod {modulus})) {q} {mu} {D}
    (fun i : Fin {Q} => PaperKernel.taylorJets {modulus} hist i.val {D})

def exact : Nat := (result.1.headD 0).val

#eval ((result.1.take {Q*D}).map ZMod.val) == hist
#eval exact
#eval exact == {H[0]}
#eval result.2

end VECrtGenerated
'''
    outfile.write_text(module)
    return outfile,n,m,Q,modulus,H,stats


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('cnf',type=pathlib.Path)
    p.add_argument('--prime',type=int,required=True)
    p.add_argument('--precision',type=int,required=True)
    p.add_argument('--order',type=int,default=3)
    p.add_argument('--timeout',type=int,default=115)
    args=p.parse_args()
    src=args.cnf.resolve()
    out,n,m,Q,pmod,hist,stats=generate(src,args.prime,args.precision,args.order)
    leanpath=subprocess.check_output([str(pathlib.Path.home()/'.elan/bin/lake'),'env','printenv','LEAN_PATH'],cwd=PROJECT,text=True,env=dict(os.environ,ELAN_TOOLCHAIN='eth-lean-4.34.1')).strip()
    env=os.environ.copy()
    env.update(ELAN_TOOLCHAIN='eth-lean-4.34.1',ELAN_NO_OVERRIDE_NOTICE='1',
               PATH=str(pathlib.Path.home()/'.elan/bin')+':'+env.get('PATH',''),
               LEAN_PATH=leanpath+':'+str(EXPERIMENT)+':'+str(ROOT)+':'+str(ROOT/'generated'))
    t=time.perf_counter()
    res=subprocess.run(['lean',str(out)],cwd=ROOT,capture_output=True,text=True,
                       env=env,timeout=args.timeout)
    (out.with_suffix('.log')).write_text(res.stdout+'\n'+res.stderr)
    lines=[line.strip() for line in res.stdout.splitlines() if line.strip()]
    print('LEAN_STDOUT:',lines)
    if res.returncode!=0 or len(lines)<4 or lines[-4]!='true' or lines[-2]!='true':
        raise AssertionError('Original Lean Hermite code failed matching the VE histogram; see '+str(out.with_suffix('.log')))
    assert int(lines[-3])==hist[0]
    info={'cnf':str(src),'generated_lean':str(out),'n':n,'m':m,'Q':Q,'D':args.order,
          'prime':args.prime,'precision':args.precision,'modulus':pmod,'count':hist[0],
          'crt_scalar_callbacks':int(lines[-1]),
          'lean_wall_s':round(time.perf_counter()-t,4),'ve_stats':stats,
          'all_coefficients_recovered':True,'source_kernel':'OpenAI Reconstruction.run',
          'caution':'VE Python sampler is tested, but not yet formally verified'}
    out.with_suffix('.json').write_text(json.dumps(info,indent=2)+'\n')
    print(json.dumps(info,indent=2))

if __name__=='__main__':main()
